"""Table definitions for the Household Mail Survey (HMS) report layout.

Each entry tells the parser how to turn one printed table into tidy rows.
Every row becomes a point keyed by (topic, dimension, segment, year).

Modes
-----
years      Columns are survey years (e.g. 2015 2020 2025 [+ two "% change" columns]).
columns    A single-year table; `columns` names the topic each numeric column feeds.

Row roles
---------
Group header lines (exact text, see `groups`) switch the current dimension
(or topic / segment, depending on `group_role`). The row matching `total`
is recorded under dimension "Overall", segment "All households".
"""

